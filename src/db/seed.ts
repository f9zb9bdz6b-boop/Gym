export async function ensureDatabaseSeeded(): Promise<void> {
  const exCount = await db.exerciseLibrary.count();
  if (exCount === 0) {
    await db.exerciseLibrary.bulkAdd(SEED_EXERCISES);
  }

  const foodCount = await db.foodItems.count();
  if (foodCount === 0) {
    await db.foodItems.bulkAdd(SEED_FOODS);
  }

  const planCount = await db.workoutPlans.count();
  if (planCount === 0) {
    await db.workoutPlans.bulkAdd(SEED_WORKOUT_PLANS);
  }

  const goalCount = await db.dailyGoals.count();
  if (goalCount === 0) {
    await db.dailyGoals.bulkAdd(SEED_GOALS);
  }

  const settings = await db.appSettings.get('settings');
  if (!settings) {
    await db.appSettings.put({
      id: 'settings',
      weightUnit: 'kg',
      aiProvider: 'local_deterministic',
      aiConsentGranted: false,
      schemaVersion: 1,
      updatedAt: new Date().toISOString(),
    });
  }
}
